#!/bin/bash
# Build Aurora's own .deb packages from desktop/ and branding/.
# Usage: package-desktop.sh SOURCE_DIR OUTPUT_DIR VERSION
#
#   aurora-desktop  the shell, apps, settings, greeter, data and translations
#   aurora-artwork  wallpapers and session sounds (big, and they rarely change)
#
# Installed systems get them, and their updates, from the Aurora apt
# repository (see tools/publish-apt.sh).
set -euo pipefail
src=$1 out=$2 version=$3
stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT

make -s -C "$src/desktop" install DESTDIR="$stage/desktop" PREFIX=/usr

mkdir -p "$stage/artwork/usr/share"
mv "$stage/desktop/usr/share/backgrounds" "$stage/artwork/usr/share/"
mv "$stage/desktop/usr/share/sounds" "$stage/artwork/usr/share/"
find "$stage" -name __pycache__ -prune -exec rm -rf {} +

control() {  # control NAME ROOT DEPENDS DESCRIPTION
    local name=$1 root=$2 depends=$3 desc=$4
    mkdir -p "$root/DEBIAN" "$root/usr/share/doc/$name"
    cp "$src/LICENSE" "$root/usr/share/doc/$name/copyright" 2>/dev/null || true
    local size
    size=$(du -sk --exclude=DEBIAN "$root" | cut -f1)
    cat > "$root/DEBIAN/control" <<CONTROL
Package: $name
Version: $version
Architecture: all
Maintainer: Luca Padovan <padovan.93@gmail.com>
Installed-Size: $size
Depends: $depends
Section: x11
Priority: optional
Homepage: https://github.com/padovanl/auroraOS
Description: $desc
CONTROL
}

control aurora-desktop "$stage/desktop" \
    "python3, python3-gi, python3-gi-cairo, python3-cairo, python3-pywayland, python3-cffi-backend, gir1.2-gtk-4.0, gir1.2-adw-1, gir1.2-gtk4layershell-1.0, libgtk4-layer-shell0, gir1.2-nm-1.0, gir1.2-upowerglib-1.0, gir1.2-gtksource-5, gir1.2-poppler-0.18, papirus-icon-theme, labwc, greetd, wl-clipboard, grim, slurp, wlsunset, swayidle, gtklock, pipewire-bin, aurora-artwork (>= ${version%.*})" \
    "Aurora desktop environment
 The shell (menu bar, dock, Spotlight, Launchpad, Control Center,
 notifications, overview), Settings, Files, Dev Hub, the login screen,
 Quick Look and the Aurora AI assistant, written in Python and GTK 4 for
 the labwc Wayland compositor."

control aurora-artwork "$stage/artwork" "" \
    "Aurora wallpapers and session sounds
 The Aurora landscapes (including the dynamic set that follows the sun)
 and the startup and shutdown sounds, all generated by code."
sed -i '/^Depends: $/d' "$stage/artwork/DEBIAN/control"

mkdir -p "$out"
rm -f "$out"/aurora-desktop_*.deb "$out"/aurora-artwork_*.deb
dpkg-deb --root-owner-group -Zxz --build "$stage/desktop" "$out/aurora-desktop_${version}_all.deb" >/dev/null
dpkg-deb --root-owner-group -Zxz --build "$stage/artwork" "$out/aurora-artwork_${version}_all.deb" >/dev/null
ls -1 "$out"/aurora-*.deb
